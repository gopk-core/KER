#!/bin/bash
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
VER=$(PYTHONPATH="$ROOT/python" python3 -c 'from ker import __version__; print(__version__)')
ARCH=${1:-amd64}
python3 - "$ROOT" "$VER" "$ARCH" << 'PY'
import hashlib, io, json, os, stat, sys, tarfile, tempfile, time
from pathlib import Path

root, ver, arch = sys.argv[1:]
meta = json.loads((Path(root) / "packaging/arches.json").read_text())
apk_arch = meta[arch]["apk"]
stage = Path(tempfile.mkdtemp(prefix="ker-apk-"))
try:
    import subprocess
    subprocess.check_call([str(Path(root) / "packaging/stage.sh"), str(stage), arch], stdout=subprocess.DEVNULL)
    # data.tar.gz
    data_buf = io.BytesIO()
    files_size = 0
    with tarfile.open(fileobj=data_buf, mode="w:gz", format=tarfile.GNU_FORMAT, dereference=False) as tf:
        for dirpath, dirnames, filenames in os.walk(stage):
            dirnames.sort()
            rel_dir = os.path.relpath(dirpath, stage)
            # add directory
            if rel_dir != ".":
                info = tf.gettarinfo(dirpath, arcname="./" + rel_dir.replace("\\", "/"))
                info.uid = 0
                info.gid = 0
                info.uname = "root"
                info.gname = "root"
                tf.addfile(info)
            for name in sorted(filenames):
                path = Path(dirpath) / name
                if path.is_symlink() or not path.is_file():
                    continue
                arc = "./" + str(path.relative_to(stage)).replace("\\", "/")
                info = tf.gettarinfo(str(path), arcname=arc)
                info.uid = 0
                info.gid = 0
                info.uname = "root"
                info.gname = "root"
                files_size += path.stat().st_size
                with path.open("rb") as f:
                    tf.addfile(info, f)
    data_bytes = data_buf.getvalue()
    datahash = hashlib.sha256(data_bytes).hexdigest()

    scripts = Path(root) / "packaging" / "scripts"
    control_dir = Path(tempfile.mkdtemp(prefix="ker-apk-ctl-"))
    pkginfo = f"""# Generated by packaging/build-apk.sh
pkgname = ker
pkgver = {ver}-r0
pkgdesc = Linux media-backed kernel authorization system
url = https://localhost/ker
arch = {apk_arch}
license = AGPL-3.0-or-later
maintainer = KER
origin = ker
builddate = {int(time.time())}
size = {files_size}
datahash = {datahash}
"""
    (control_dir / ".PKGINFO").write_text(pkginfo)
    # Alpine script names
    (control_dir / ".pre-install").write_bytes((scripts / "preinst.sh").read_bytes())
    (control_dir / ".post-install").write_bytes((scripts / "postinst.sh").read_bytes())
    (control_dir / ".pre-upgrade").write_bytes((scripts / "preinst.sh").read_bytes())
    (control_dir / ".post-upgrade").write_bytes((scripts / "postinst.sh").read_bytes())
    (control_dir / ".pre-deinstall").write_bytes((scripts / "prerm.sh").read_bytes())
    (control_dir / ".post-deinstall").write_bytes((scripts / "postrm.sh").read_bytes())
    for n in (".pre-install", ".post-install", ".pre-upgrade", ".post-upgrade", ".pre-deinstall", ".post-deinstall"):
        os.chmod(control_dir / n, 0o755)

    ctl_buf = io.BytesIO()
    with tarfile.open(fileobj=ctl_buf, mode="w:gz", format=tarfile.GNU_FORMAT) as tf:
        for name in [".PKGINFO", ".pre-install", ".post-install", ".pre-upgrade",
                     ".post-upgrade", ".pre-deinstall", ".post-deinstall"]:
            path = control_dir / name
            info = tf.gettarinfo(str(path), arcname=name)
            info.uid = 0
            info.gid = 0
            info.uname = "root"
            info.gname = "root"
            with path.open("rb") as f:
                tf.addfile(info, f)
    ctl_bytes = ctl_buf.getvalue()

    outdir = Path(root) / "dist"
    outdir.mkdir(exist_ok=True)
    out = outdir / f"ker-{ver}-r0.{apk_arch}.apk"
    # Unsigned APK: control + data. Install with apk add --allow-untrusted
    # (or `ker upgrade --trust-package`).
    with out.open("wb") as f:
        f.write(ctl_bytes)
        f.write(data_bytes)
    os.chmod(out, 0o644)
    print(out)
finally:
    import shutil
    shutil.rmtree(stage, ignore_errors=True)
    if "control_dir" in dir():
        shutil.rmtree(control_dir, ignore_errors=True)
PY
